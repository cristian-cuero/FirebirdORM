import { QueryGenerator } from '../query/query-generator.js';

/**
 * Dialecto SQL específico para Firebird
 * Adapta la generación de SQL según la versión detectada del servidor
 */
export class Dialect {
  /**
   * @param {object} connectionManager
   */
  constructor(connectionManager) {
    this.connectionManager = connectionManager;
    this.version = null;
    this.versionParts = null;
    // Inicializamos el generador de consultas con este dialecto
    this.queryGenerator = new QueryGenerator(this);
  }

  /**
   * Detecta la versión del servidor Firebird
   * @returns {Promise<string>} Versión detectada (ej: '3.0.14.33856')
   */
  async detectVersion() {
    const result = await this.connectionManager.execute(
      "SELECT rdb$get_context('SYSTEM', 'ENGINE_VERSION') as version FROM rdb$database"
    );
    this.version = result[0]?.VERSION || '3.0.0';
    this.versionParts = this.version.split('.').map(Number);
    return this.version;
  }

  /**
   * Verifica si soporta una característica
   * @param {string} feature - Característica a verificar
   */
  supports(feature) {
    if (!this.versionParts) return false;

    const major = this.versionParts[0];
    const minor = this.versionParts[1] || 0;

    switch (feature) {
      case 'identity': // IDENTITY columns (auto-increment)
        return major >= 4;
      case 'returning': // RETURNING clause
        return major >= 3;
      case 'boolean': // BOOLEAN type
        return major >= 3;
      case 'window_functions': // Window functions
        return major >= 3;
      case 'cte': // Common Table Expressions
        return major >= 3;
      case 'merge': // MERGE statement
        return major >= 3;
      case 'truncate': // TRUNCATE TABLE
        return major >= 3;
      default:
        return false;
    }
  }

  /**
   * Genera SQL para PK auto-incremental
   * @param {string} columnName
   * @param {string} tableName
   */
  getIdentityColumnSQL(columnName, tableName) {
    if (this.supports('identity')) {
      // Firebird 4+: IDENTITY
      return `${columnName} INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    }
    // Firebird 2.5/3.0: Generator + Trigger
    return `${columnName} INTEGER NOT NULL PRIMARY KEY`;
  }

  /**
   * Genera SQL para crear generador (FB 2.5/3.0)
   * @param {string} tableName
   * @param {string} columnName
   */
  getGeneratorSQL(tableName, columnName) {
    if (!this.supports('identity')) {
      return `CREATE GENERATOR GEN_${tableName.toUpperCase()}_${columnName.toUpperCase()};`;
    }
    return '';
  }

  /**
   * Genera trigger para PK (FB 2.5/3.0)
   * @param {string} tableName
   * @param {string} columnName
   */
  getTriggerSQL(tableName, columnName) {
    if (!this.supports('identity')) {
      return `
        SET TERM ^ ;
        CREATE TRIGGER BI_${tableName.toUpperCase()}_${columnName.toUpperCase()} FOR ${tableName}
        ACTIVE BEFORE INSERT POSITION 0
        AS
        BEGIN
          IF (NEW.${columnName} IS NULL) THEN
            NEW.${columnName} = GEN_ID(GEN_${tableName.toUpperCase()}_${columnName.toUpperCase()}, 1);
        END^
        SET TERM ; ^`;
    }
    return '';
  }

  /**
   * Obtiene la sintaxis para RETURNING
   */
  getReturningSQL(columns = '*') {
    if (this.supports('returning')) {
      return `RETURNING ${columns}`;
    }
    return '';
  }

  /**
   * Obtiene el tipo de dato para BOOLEAN
   */
  getBooleanType() {
    if (this.supports('boolean')) {
      return 'BOOLEAN';
    }
    return 'SMALLINT'; // Fallback FB 2.5
  }

  /**
   * Obtiene límites de paginación
   * @param {number} limit
   * @param {number} offset
   */
  getLimitOffsetSQL(limit, offset) {
    if (this.versionParts && this.versionParts[0] >= 4) {
      // Firebird 4+: OFFSET ... ROWS FETCH NEXT ... ROWS ONLY
      let sql = '';
      if (offset > 0) {
        sql += ` OFFSET ${offset} ROWS`;
      }
      if (limit > 0) {
        sql += ` FETCH NEXT ${limit} ROWS ONLY`;
      }
      return sql;
    }
    // Firebird 2.5/3.0: FIRST ... SKIP ...
    let sql = '';
    if (limit > 0) {
      sql += ` FIRST ${limit}`;
    }
    if (offset > 0) {
      sql += ` SKIP ${offset}`;
    }
    return sql;
  }
}
