import { DataTypes } from '../core/data-types.js';
import { QueryGenerator } from '../query/query-generator.js';

/**
 * QueryInterface - API para ejecutar operaciones DDL (Data Definition Language)
 * desde migraciones sin escribir SQL crudo.
 *
 * Uso típico en migraciones:
 *   up(queryInterface) {
 *     return queryInterface.createTable('users', { ... });
 *   }
 */
export class QueryInterface {
  constructor(sequelize) {
    this.sequelize = sequelize;
    this.queryGenerator = new QueryGenerator(sequelize.dialect);
  }

  /**
   * Genera la definición SQL de una columna a partir de la definición de DataTypes
   */
  _getColumnSql(columnName, definition) {
    let sql = `"${columnName}" `;

    // Obtener tipo SQL
    if (definition.type && typeof definition.type.toSql === 'function') {
      sql += definition.type.toSql();
    } else if (typeof definition === 'function') {
      // Si es un DataType directo (ej: DataTypes.STRING(50))
      const dt = definition();
      sql += dt.toSql();
    } else if (definition.type && definition.type.key) {
      // Si es un objeto con tipo
      sql += definition.type.key;
      if (definition.type.options?.length) {
        sql += `(${definition.type.options.length})`;
      }
    } else {
      throw new Error(`Definición de tipo inválida para columna ${columnName}`);
    }

    // Constraints
    if (definition.primaryKey) sql += ' PRIMARY KEY';
    if (definition.allowNull === false) sql += ' NOT NULL';
    if (definition.unique) sql += ' UNIQUE';
    if (definition.defaultValue !== undefined) {
      const defaultVal = this._formatDefaultValue(definition.defaultValue, definition.type);
      sql += ` DEFAULT ${defaultVal}`;
    }
    if (definition.autoIncrement) sql += ' GENERATED BY DEFAULT AS IDENTITY'; // FB 3.0+

    return sql;
  }

  _formatDefaultValue(value, type) {
    if (value === null) return 'NULL';
    if (typeof value === 'function') return value(); // ej: DataTypes.NOW
    if (typeof value === 'string') return `'${value}'`;
    if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
    return value;
  }

  /**
   * Crea una nueva tabla
   * @param {string} tableName - Nombre de la tabla
   * @param {object} attributes - Definición de columnas { nombre: { type, allowNull, ... } }
   * @param {object} options - Opciones adicionales
   */
  async createTable(tableName, attributes, options = {}) {
    const columnsSql = Object.entries(attributes).map(([name, def]) =>
      this._getColumnSql(name, def)
    ).join(', ');

    // Firebird: CREATE TABLE tabla (col1, col2, ...)
    const sql = `CREATE TABLE "${tableName}" (${columnsSql})`;

    return this.sequelize.query(sql);
  }

  /**
   * Elimina una tabla
   */
  async dropTable(tableName, options = {}) {
    const sql = options.ifExists
      ? `DROP TABLE IF EXISTS "${tableName}"`
      : `DROP TABLE "${tableName}"`;

    return this.sequelize.query(sql);
  }

  /**
   * Añade una columna a una tabla existente
   */
  async addColumn(tableName, columnName, definition) {
    const columnSql = this._getColumnSql(columnName, definition);
    const sql = `ALTER TABLE "${tableName}" ADD ${columnSql}`;
    return this.sequelize.query(sql);
  }

  /**
   * Elimina una columna
   */
  async removeColumn(tableName, columnName) {
    const sql = `ALTER TABLE "${tableName}" DROP "${columnName}"`;
    return this.sequelize.query(sql);
  }

  /**
   * Renombra una columna
   */
  async renameColumn(tableName, oldName, newName) {
    const sql = `ALTER TABLE "${tableName}" ALTER "${oldName}" TO "${newName}"`;
    return this.sequelize.query(sql);
  }

  /**
   * Cambia la definición de una columna (tipo, constraints, etc)
   */
  async changeColumn(tableName, columnName, definition) {
    const columnSql = this._getColumnSql(columnName, definition);
    // Firebird: ALTER TABLE ... ALTER COLUMN ... TYPE ...
    const sql = `ALTER TABLE "${tableName}" ALTER "${columnName}" TYPE ${definition.type.toSql()}`;

    // Nota: Cambiar NOT NULL/NULL requiere ALTER COLUMN ... SET/DROP NOT NULL por separado
    let constraints = '';
    if (definition.allowNull === false) constraints += ' SET NOT NULL';
    if (definition.allowNull === true) constraints += ' DROP NOT NULL';
    if (definition.defaultValue !== undefined) {
      constraints += ` SET DEFAULT ${this._formatDefaultValue(definition.defaultValue, definition.type)}`;
    }

    if (constraints) {
      // Ejecutar en dos pasos para Firebird
      await this.sequelize.query(sql);
      return this.sequelize.query(`ALTER TABLE "${tableName}" ALTER "${columnName}"${constraints}`);
    }

    return this.sequelize.query(sql);
  }

  /**
   * Crea un índice
   */
  async addIndex(tableName, columns, options = {}) {
    const indexName = options.name || `${tableName}_${Array.isArray(columns) ? columns.join('_') : columns}_idx`;
    const unique = options.unique ? 'UNIQUE ' : '';
    const columnsList = Array.isArray(columns) ? columns.map(c => `"${c}"`).join(', ') : `"${columns}"`;

    const sql = `CREATE ${unique}INDEX "${indexName}" ON "${tableName}" (${columnsList})`;
    return this.sequelize.query(sql);
  }

  /**
   * Elimina un índice
   */
  async removeIndex(tableName, indexName) {
    const sql = `DROP INDEX "${indexName}"`;
    return this.sequelize.query(sql);
  }

  /**
   * Renombra una tabla
   */
  async renameTable(oldName, newName) {
    const sql = `ALTER TABLE "${oldName}" RENAME TO "${newName}"`;
    return this.sequelize.query(sql);
  }

  /**
   * Ejecuta SQL crudo (para casos especiales)
   */
  async query(sql, params = []) {
    return this.sequelize.query(sql, params);
  }

  /**
   * Verifica si una tabla existe
   */
  async tableExists(tableName) {
    const sql = `
      SELECT 1 FROM RDB\$RELATIONS
      WHERE RDB\$RELATION_NAME = UPPER(?)
      AND RDB\$VIEW_BLR IS NULL
      AND (RDB\$SYSTEM_FLAG IS NULL OR RDB\$SYSTEM_FLAG = 0)
    `;
    const result = await this.sequelize.query(sql, [tableName.toUpperCase()]);
    return result.length > 0;
  }

  /**
   * Verifica si una columna existe
   */
  async columnExists(tableName, columnName) {
    const sql = `
      SELECT 1 FROM RDB\$RELATION_FIELDS
      WHERE RDB\$RELATION_NAME = UPPER(?)
      AND RDB\$FIELD_NAME = UPPER(?)
    `;
    const result = await this.sequelize.query(sql, [tableName.toUpperCase(), columnName.toUpperCase()]);
    return result.length > 0;
  }
}