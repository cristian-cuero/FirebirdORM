import { QueryInterface } from '../../../src/migrations/query-interface.js';
import { DataTypes } from '../../../src/core/data-types.js';

// Mock de sequelize
const createMockSequelize = () => ({
  query: jest.fn().mockResolvedValue([]),
  dialect: {}
});

describe('QueryInterface - Migraciones', () => {
  let queryInterface;
  let mockSequelize;

  beforeEach(() => {
    mockSequelize = createMockSequelize();
    queryInterface = new QueryInterface(mockSequelize);
  });

  describe('createTable', () => {
    test('Debe generar SQL CREATE TABLE con columnas básicas', async () => {
      await queryInterface.createTable('users', {
        id: { type: DataTypes.INTEGER, primaryKey: true },
        name: { type: DataTypes.STRING(50), allowNull: false }
      });

      expect(mockSequelize.query).toHaveBeenCalled();
      const call = mockSequelize.query.mock.calls[0];
      const sql = call[0];

      expect(sql).toContain('CREATE TABLE "users"');
      expect(sql).toContain('"id" INTEGER PRIMARY KEY');
      expect(sql).toContain('"name" VARCHAR(50) NOT NULL');
    });

    test('Debe manejar autoIncrement como GENERATED BY DEFAULT AS IDENTITY', async () => {
      await queryInterface.createTable('products', {
        id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true }
      });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toContain('GENERATED BY DEFAULT AS IDENTITY');
    });

    test('Debe manejar defaultValue', async () => {
      await queryInterface.createTable('items', {
        status: { type: DataTypes.STRING(20), defaultValue: 'active' },
        count: { type: DataTypes.INTEGER, defaultValue: 0 },
        is_valid: { type: DataTypes.BOOLEAN, defaultValue: true }
      });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toContain("DEFAULT 'active'");
      expect(sql).toContain('DEFAULT 0');
      expect(sql).toContain('DEFAULT TRUE');
    });

    test('Debe manejar unique constraint', async () => {
      await queryInterface.createTable('emails', {
        email: { type: DataTypes.STRING(100), unique: true }
      });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toContain('UNIQUE');
    });
  });

  describe('dropTable', () => {
    test('Debe generar DROP TABLE simple', async () => {
      await queryInterface.dropTable('old_table');

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('DROP TABLE "old_table"');
    });

    test('Debe generar DROP TABLE IF EXISTS', async () => {
      await queryInterface.dropTable('maybe_table', { ifExists: true });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('DROP TABLE IF EXISTS "maybe_table"');
    });
  });

  describe('addColumn', () => {
    test('Debe generar ALTER TABLE ADD COLUMN', async () => {
      await queryInterface.addColumn('users', 'email', { type: DataTypes.STRING(100) });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('ALTER TABLE "users" ADD "email" VARCHAR(100)');
    });
  });

  describe('removeColumn', () => {
    test('Debe generar ALTER TABLE DROP COLUMN', async () => {
      await queryInterface.removeColumn('users', 'old_field');

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('ALTER TABLE "users" DROP "old_field"');
    });
  });

  describe('renameColumn', () => {
    test('Debe generar ALTER TABLE ALTER COLUMN TO', async () => {
      await queryInterface.renameColumn('users', 'name', 'full_name');

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('ALTER TABLE "users" ALTER "name" TO "full_name"');
    });
  });

  describe('addIndex', () => {
    test('Debe generar CREATE INDEX', async () => {
      await queryInterface.addIndex('users', ['email', 'status']);

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toContain('CREATE INDEX');
      expect(sql).toContain('ON "users"');
      expect(sql).toContain('"email", "status"');
    });

    test('Debe generar CREATE UNIQUE INDEX', async () => {
      await queryInterface.addIndex('users', 'email', { unique: true, name: 'ux_users_email' });

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toContain('CREATE UNIQUE INDEX "ux_users_email"');
    });
  });

  describe('removeIndex', () => {
    test('Debe generar DROP INDEX', async () => {
      await queryInterface.removeIndex('users', 'ux_users_email');

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('DROP INDEX "ux_users_email"');
    });
  });

  describe('renameTable', () => {
    test('Debe generar ALTER TABLE RENAME TO', async () => {
      await queryInterface.renameTable('old_name', 'new_name');

      const sql = mockSequelize.query.mock.calls[0][0];
      expect(sql).toBe('ALTER TABLE "old_name" RENAME TO "new_name"');
    });
  });

  describe('tableExists', () => {
    test('Debe consultar RDB$RELATIONS', async () => {
      mockSequelize.query.mockResolvedValue([{ 1: 1 }]);

      const exists = await queryInterface.tableExists('users');

      expect(exists).toBe(true);
      expect(mockSequelize.query).toHaveBeenCalledWith(
        expect.stringContaining('RDB$RELATIONS'),
        ['USERS']
      );
    });

    test('Debe retornar false si no existe', async () => {
      mockSequelize.query.mockResolvedValue([]);

      const exists = await queryInterface.tableExists('nonexistent');
      expect(exists).toBe(false);
    });
  });

  describe('columnExists', () => {
    test('Debe consultar RDB$RELATION_FIELDS', async () => {
      mockSequelize.query.mockResolvedValue([{ 1: 1 }]);

      const exists = await queryInterface.columnExists('users', 'email');

      expect(exists).toBe(true);
      expect(mockSequelize.query).toHaveBeenCalledWith(
        expect.stringContaining('RDB$RELATION_FIELDS'),
        ['USERS', 'EMAIL']
      );
    });
  });
});